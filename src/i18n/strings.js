// Turn an eligibility rule into a sentence, for example "Age 21–24 years".
// "lang" picks the language, "label" turns an option key into text.
export function ruleText(rule, lang, label) {
  const p = rule.params
  const hi = lang === 'hi'
  const list = (group, keys) => keys.map((k) => label(group, k)).join(' / ')

  switch (rule.key) {
    case 'age':
      if (p.min && p.max) return hi ? `उम्र ${p.min}–${p.max} साल` : `Age ${p.min}–${p.max} years`
      if (p.min) return hi ? `उम्र कम से कम ${p.min} साल` : `Age ${p.min}+ years`
      return hi ? `उम्र ${p.max} साल तक` : `Age up to ${p.max} years`
    case 'education':
      return (hi ? 'पढ़ाई: ' : 'Education: ') + list('education', p.allowed)
    case 'stream':
      return (hi ? 'स्ट्रीम: ' : 'Stream: ') + list('stream', p.allowed)
    case 'gender':
      return hi ? 'सिर्फ़ लड़कियों के लिए' : 'Only for girls'
    case 'category':
      return (hi ? 'श्रेणी: ' : 'Category: ') + list('category', p.allowed)
    case 'income':
      return hi ? `परिवार की आय ₹${p.max} लाख/साल तक` : `Family income up to ₹${p.max} lakh/year`
    case 'marks':
      return hi ? `कम से कम ${p.min}% नंबर` : `At least ${p.min}% marks`
    case 'notEmployed':
      return hi ? 'अभी फ़ुल-टाइम नौकरी नहीं होनी चाहिए' : 'Should not have a full-time job now'
    default:
      return rule.key
  }
}

